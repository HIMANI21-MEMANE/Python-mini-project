import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

print("="*60)
print("  MINI PROJECT: SMART E-COMMERCE SALES & BEHAVIOR ANALYTICS")
print("="*60 + "\n")

# =====================================================================
# PART 1 (Syllabus Item 1): Create a Structured Dataset using NumPy & Pandas
# =====================================================================
print("[Step 1] Simulating and Creating raw transaction logs...")

# Generating synthetic warehouse/sales records using NumPy
np.random.seed(42)  # Ensures consistent random data generation
total_records = 200

transaction_ids = np.arange(1001, 1001 + total_records)
categories = np.random.choice(['Electronics', 'Clothing', 'Home Decor', 'Books'], size=total_records, p=[0.3, 0.3, 0.2, 0.2])
units_sold = np.random.randint(1, 6, size=total_records)
unit_prices = np.round(np.random.uniform(10.0, 500.0, size=total_records), 2)
customer_ratings = np.round(np.random.uniform(1.0, 5.0, size=total_records), 1)

# Building the Pandas DataFrame (Combining NumPy arrays into a central ledger)
sales_raw_df = pd.DataFrame({
    'TransactionID': transaction_ids,
    'Category': categories,
    'UnitsSold': units_sold,
    'UnitPrice': unit_prices,
    'Rating': customer_ratings
})

# Save to a local CSV file to simulate an "existing dataset" for Part 2
sales_raw_df.to_csv('ecommerce_sales.csv', index=False)
print("✔ Base DataFrame successfully established and saved as 'ecommerce_sales.csv'.\n")


# =====================================================================
# PART 2 (Syllabus Item 2): Import Dataset and Perform Analytical Operations
# =====================================================================
print("[Step 2] Importing dataset and executing business intelligence operations...")

# Importing the dataset we just saved
sales_df = pd.read_csv('ecommerce_sales.csv')

# Operation A: Feature Engineering (Calculate Total Revenue)
sales_df['TotalRevenue'] = sales_df['UnitsSold'] * sales_df['UnitPrice']

# Operation B: Categorical Aggregation & Grouping
print("\n--- Summary Performance Metrics per Product Category ---")
category_summary = sales_df.groupby('Category').agg(
    Total_Units=('UnitsSold', 'sum'),
    Average_Price=('UnitPrice', 'mean'),
    Total_Sales_Revenue=('TotalRevenue', 'sum'),
    Average_Rating=('Rating', 'mean')
).round(2)
print(category_summary)

# Operation C: Data Filtering (Extracting high-value, highly-rated transactions)
premium_sales = sales_df[(sales_df['TotalRevenue'] > 500) & (sales_df['Rating'] >= 4.0)]
print(f"\n✔ Filtered {len(premium_sales)} premium transactions (Revenue > $500 & Rating >= 4.0).")


# =====================================================================
# PART 3 (Syllabus Item 3): Data Visualization Dashboard using Matplotlib
# =====================================================================
print("\n[Step 3] Rendering the interactive executive dashboard...")

# Setting up a dashboard layout canvas
fig, axes = plt.subplots(2, 2, figsize=(14, 10))
fig.suptitle('E-Commerce Performance & Analytics Dashboard', fontsize=16, fontweight='bold', y=0.95)

# Graph 1: Bar Chart (Total Revenue generated by each Product Category)
axes[0, 0].bar(category_summary.index, category_summary['Total_Sales_Revenue'], color=['#3498db', '#2ecc71', '#e74c3c', '#f1c40f'], edgecolor='black')
axes[0, 0].set_title('Revenue Generation by Category', fontsize=12, fontweight='bold')
axes[0, 0].set_ylabel('Total Revenue ($)')
axes[0, 0].grid(axis='y', linestyle='--', alpha=0.7)

# Graph 2: Scatter Plot (Relationship between Unit Price and Customer Ratings)
scatter = axes[0, 1].scatter(sales_df['UnitPrice'], sales_df['Rating'], c=sales_df['TotalRevenue'], cmap='viridis', alpha=0.6, edgecolor='none')
axes[0, 1].set_title('Product Price vs. Customer Ratings', fontsize=12, fontweight='bold')
axes[0, 1].set_xlabel('Unit Price ($)')
axes[0, 1].set_ylabel('Rating (1-5 Stars)')
fig.colorbar(scatter, ax=axes[0, 1], label='Transaction Value ($)')

# Graph 3: Histogram (Distribution of Units Sold across transactions)
axes[1, 0].hist(sales_df['UnitsSold'], bins=np.arange(1, 7)-0.5, rwidth=0.8, color='#9b59b6', edgecolor='black', alpha=0.8)
axes[1, 0].set_title('Distribution Order Sizes', fontsize=12, fontweight='bold')
axes[1, 0].set_xlabel('Units Sold Per Transaction')
axes[1, 0].set_ylabel('Frequency Count')
axes[1, 0].set_xticks(range(1, 6))

# Graph 4: Pie Chart (Market Share of Units Sold per Category)
axes[1, 1].pie(category_summary['Total_Units'], labels=category_summary.index, autopct='%1.1f%%', startangle=140, colors=['#34495e', '#1abc9c', '#e67e22', '#95a5a6'], explode=(0.05, 0, 0, 0))
axes[1, 1].set_title('Market Share (Total Volume Sold)', fontsize=12, fontweight='bold')

# Fine-tune layout and deploy
plt.tight_layout(rect=[0, 0, 1, 0.92])
print("✔ Dashboard drawn successfully. Closing the chart window will safely end the script.")
plt.show()

print("\n" + "="*60)
print("  PROJECT EXECUTION COMPLETE")
print("="*60)
